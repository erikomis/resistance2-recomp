#!/usr/bin/env python3
"""Extract and lift Resistance 2's raw-SPU programs from EBOOT.elf.

igInitRawSpu (the 320-byte loader both raw SPUs start with, see
prepare_r2_rawspu_loader.py) DMAs these bodies from the EBOOT into local
store at 0x200 and enters them at 0x230: the Bink decoder for movies and two
programs the levels run every frame. They are raw SPU bytes behind a DEADDEAD
header, not ELFs, so the image scanner never sees them and they ran in the
interpreter (movies at ~3 FPS). Each is checked against its FNV-1a pin,
lifted at LS 0x200 into port/spu/r2_<name>/ (spu_recomp.c/.h, image.bin,
functions.json, lift.json: translated game code, .gitignore'd) and given a
generated register.c that registers it as a resident code region keyed on
its source EA. Re-run cmake afterwards.

  tools/prepare_r2_rawspu.py                  # extract and lift all three
  tools/prepare_r2_rawspu.py --only bink      # one of them
  tools/prepare_r2_rawspu.py --check          # the lifted images match the EBOOT
"""
import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import r2_layout  # noqa: E402

LS_BASE = 0x200
# name: SPU image id. Where each program sits in the EBOOT, its size and its
# FNV-1a are per build of the executable: r2_layout.EBOOT_BUILDS.
PROGRAMS = {"bink": 910004, "rawspu_a": 910005, "rawspu_b": 910006}


def register_c(name, va, size, image_id):
    return f"""/* Resistance 2 raw-SPU program "{name}" embedded as raw data in EBOOT.elf.
 * EBOOT VA 0x{va:08X}, 0x{size:X} bytes, which igInitRawSpu streams into
 * local store at 0x{LS_BASE:X} and enters at 0x230. Not an ELF, so it is matched
 * by source EA when that first chunk lands, not by fingerprint.
 * GENERATED by tools/prepare_r2_rawspu.py. */
#include <stdint.h>

extern void spu_begin_image(int image_id);
extern void spu_overlay_register_region(uint32_t content_ea, uint32_t span, int image_id);
extern void r2_{name}_spu_recomp_register(void);

__attribute__((constructor)) static void r2_{name}_register(void)
{{
    spu_begin_image({image_id});
    r2_{name}_spu_recomp_register();
    spu_overlay_register_region(0x{va:08X}u, 0x{size:X}u, {image_id});
    spu_begin_image(0);
}}
""".encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only check the current extraction")
    parser.add_argument("--only", choices=sorted(PROGRAMS), action="append",
                        help="limit to this program (repeatable)")
    parser.add_argument("--eboot", type=Path, default=r2_layout.eboot())
    parser.add_argument("--spu-dir", type=Path, default=r2_layout.SPU_DIR,
                        help="where the r2_<name>/ folders go (default: port/spu)")
    parser.add_argument("--toolkit", type=Path, default=None, help="default: PS3RECOMP_DIR or ./ps3recomp")
    args = parser.parse_args()
    for name in args.only or PROGRAMS:
        image_id = PROGRAMS[name]
        va, size, want = r2_layout.eboot_build(args.eboot)["rawspu"][name]
        dest = args.spu_dir / f"r2_{name}"
        raw = r2_layout.eboot_bytes(args.eboot, va, size, f"the raw-SPU program {name}")
        if r2_layout.fnv1a64(raw) != want:
            raise SystemExit(f"the raw-SPU program {name}'s fingerprint differs: not the tested BCUS98120 EBOOT?")
        if args.check:
            r2_layout.check_image(dest, raw, name, "prepare_r2_rawspu.py")
            print(f"R2 raw SPU {name}: {size} bytes, FNV {want:016X}, OK")
            continue
        n = r2_layout.lift_raw(raw, dest, LS_BASE, f"r2_{name}_", args.toolkit)
        r2_layout.write_if_changed(dest / "register.c", register_c(name, va, size, image_id))
        print(f"R2 raw SPU {name} ready: {size} bytes, FNV {want:016X}, {n} functions -> {dest}")


if __name__ == "__main__":
    main()
